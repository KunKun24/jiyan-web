async function 开始上传文件() {
    if (已选文件列表.length === 0) {
        alert('请选择要上传的文件', 'warning');
        return;
    }
    
    
    
    const 上传进度区 = document.getElementById('uploadProgressArea');
    const 文件列表区域 = document.getElementById('fileListArea');
    const 文件上传面板 = document.getElementById('fileUploadPanel');
    const 上传按钮 = document.getElementById('uploadBtn');
    
    if (上传进度区) 上传进度区.style.display = 'block';
    if (文件列表区域) 文件列表区域.style.display = 'none';
    if (文件上传面板) 文件上传面板.style.display = 'none';
    if (上传按钮) 上传按钮.disabled = true;
    
    上传成功数 = 0;
    上传失败数 = 0;
    const 失败详情列表 = [];
    窗口上传结果详情 = [];
    
    当前上传队列 = 已选文件列表.map((file, index) => ({
        file, index, status: 'pending', progress: 0, speed: '0 KB/s', remaining: '计算中', xhr: null, errorMessage: '', responseData: null
    }));
    
    初始化上传进度显示(当前上传队列);
    
    const 并发数 = 3;
    let 正在上传数 = 0;
    
    async function 上传单个文件(queueItem) {
        if (queueItem.status !== 'pending') return;
        
        正在上传数++;
        queueItem.status = 'uploading';
        更新文件上传状态(queueItem.index, 'uploading');
        
        try {
            const formData = new FormData();
            formData.append('action', 'upload_so');
            formData.append('developer_username', 开发者UID);
            formData.append('password', 开发者密码);
            formData.append('token', 开发者Token);
            formData.append('app_id', 当前选中的应用ID);
            formData.append('so_file', queueItem.file);
            const 范围 = 已选文件范围[queueItem.index] || { java: 1, inject: 0 };
            formData.append('scope', JSON.stringify({ java: 范围.java ? 1 : 0, inject: 范围.inject ? 1 : 0 }));
            
            const xhr = new XMLHttpRequest();
            queueItem.xhr = xhr;
            
            const 上传开始时间 = Date.now();
            const 总文件大小 = queueItem.file.size;
            let 最后更新时间 = 上传开始时间;
            let 最后上传字节 = 0;
            let 最后速度 = 0;
            
            const uploadResult = await new Promise((resolve, reject) => {
                xhr.upload.addEventListener('progress', (event) => {
                    if (event.lengthComputable) {
                        const 当前时间 = Date.now();
                        const 已上传字节 = event.loaded;
                        const 进度 = (已上传字节 / 总文件大小) * 100;
                        queueItem.progress = 进度;
                        
                        if (最后更新时间 > 0) {
                            const 时间差秒 = Math.max(0.1, (当前时间 - 最后更新时间) / 1000);
                            const 字节差 = 已上传字节 - 最后上传字节;
                            
                            if (字节差 > 0) {
                                const 当前瞬时速度 = 字节差 / 时间差秒;
                                最后速度 = 最后速度 === 0 ? 当前瞬时速度 : (最后速度 * 0.7 + 当前瞬时速度 * 0.3);
                                
                                if (最后速度 < 1024) queueItem.speed = `${Math.round(最后速度)} B/s`;
                                else if (最后速度 < 1024 * 1024) queueItem.speed = `${(最后速度 / 1024).toFixed(1)} KB/s`;
                                else queueItem.speed = `${(最后速度 / (1024 * 1024)).toFixed(1)} MB/s`;
                                
                                const 剩余字节 = 总文件大小 - 已上传字节;
                                if (最后速度 > 0) {
                                    const 剩余时间秒 = 剩余字节 / 最后速度;
                                    if (剩余时间秒 < 1) queueItem.remaining = '<1秒';
                                    else if (剩余时间秒 < 60) queueItem.remaining = `${Math.round(剩余时间秒)}秒`;
                                    else queueItem.remaining = `${Math.floor(剩余时间秒 / 60)}分${Math.round(剩余时间秒 % 60)}秒`;
                                }
                            }
                        }
                        
                        最后更新时间 = 当前时间;
                        最后上传字节 = 已上传字节;
                        更新文件上传进度(queueItem.index, 进度, queueItem.speed, queueItem.remaining);
                        更新总进度(当前上传队列);
                    }
                });
                
                xhr.onload = function() {
                    try {
                        const 结果 = JSON.parse(xhr.responseText);
                        if (结果.success) {
                            queueItem.responseData = 结果.data;
                            resolve(结果);
                        } else {
                            reject(new Error(结果.message || '服务器返回失败'));
                        }
                    } catch (e) {
                        reject(new Error('解析服务器响应失败'));
                    }
                };
                
                xhr.onerror = function() {
                    reject(new Error('网络连接错误'));
                };
                
                xhr.ontimeout = function() {
                    reject(new Error('请求超时'));
                };
                
                xhr.open('POST', 获取API链接('Cloudupdate_上传.php'));
                xhr.timeout = 300000;
                xhr.send(formData);
            });
            
            queueItem.status = 'success';
            queueItem.errorMessage = '';
            上传成功数++;
            
            窗口上传结果详情.push({
                fileName: queueItem.file.name,
                status: 'success',
                message: '上传成功',
                fileSize: formatFileSize(queueItem.file.size),
                responseData: queueItem.responseData
            });
            
            更新文件上传状态(queueItem.index, 'success');
            
        } catch (错误) {
            queueItem.status = false;
            queueItem.errorMessage = 错误.message;
            上传失败数++;
            
            窗口上传结果详情.push({
                fileName: queueItem.file.name,
                status: false,
                message: queueItem.errorMessage,
                fileSize: formatFileSize(queueItem.file.size)
            });
            
            更新文件上传状态(queueItem.index, false, queueItem.errorMessage);
        } finally {
            正在上传数--;
            更新总进度(当前上传队列);
            继续上传();
        }
    }
    
    function 继续上传() {
        const 等待文件 = 当前上传队列.filter(item => item.status === 'pending');
        
        if (等待文件.length === 0 && 正在上传数 === 0) {
            setTimeout(() => {
                上传完成处理(上传成功数, 上传失败数);
            }, 500);
            return;
        }
        
        while (正在上传数 < 并发数 && 等待文件.length > 0) {
            const nextFile = 等待文件.shift();
            上传单个文件(nextFile);
        }
    }
    
    for (let i = 0; i < Math.min(并发数, 当前上传队列.length); i++) {
        继续上传();
    }
}

