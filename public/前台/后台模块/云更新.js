/** 外链每条链接的用途（云更新 / 注入） */
let 外链范围 = [];

/** 解析两栏文本，按行生成「链接 → 文件名 + 用途」列表 */
function 解析外链行() {
    const urlsEl = document.getElementById('remoteUrls');
    const namesEl = document.getElementById('remoteNames');
    const 列表 = document.getElementById('remoteList');
    const 空提示 = document.getElementById('remoteListEmpty');
    if (!列表) return;

    const urls = (urlsEl ? urlsEl.value : '').split(/\r?\n/).map(x => x.trim()).filter(x => x !== '');
    const names = (namesEl ? namesEl.value : '').split(/\r?\n/).map(x => x.trim()).filter(x => x !== '');
    const n = Math.min(urls.length, names.length);

    const 旧 = 外链范围;
    外链范围 = [];
    for (let i = 0; i < n; i++) {
        外链范围.push(旧[i] || { java: 默认发布范围.java, inject: 默认发布范围.inject });
    }

    if (n === 0) {
        列表.style.display = 'none';
        if (空提示) 空提示.style.display = 'block';
        return;
    }
    列表.style.display = 'block';
    if (空提示) 空提示.style.display = 'none';

    列表.innerHTML = Array.from({ length: n }, (_, i) => `
        <div data-remote-row="${i}" style="display: flex; align-items: center; gap: 10px; padding: 8px 12px; border-bottom: ${i === n - 1 ? 'none' : '1px solid #f8f9fa'};">
            <div style="font-size: 11px; color: #adb5bd; width: 18px; flex-shrink: 0;">${i + 1}</div>
            <div style="flex: 1; min-width: 0;">
                <div style="font-size: 12px; color: #333; font-weight: 500; white-space: nowrap; overflow: hidden; text-overflow: ellipsis;">${escapeHtml(names[i])}</div>
                <div style="font-size: 11px; color: #adb5bd; white-space: nowrap; overflow: hidden; text-overflow: ellipsis;">${escapeHtml(urls[i])}</div>
            </div>
            <div style="display: flex; gap: 6px; flex-shrink: 0;">
                <button type="button" data-rkind="java" data-rindex="${i}" style="padding: 4px 11px; border-radius: 13px; font-size: 12px; cursor: pointer; transition: all .15s;"></button>
                <button type="button" data-rkind="inject" data-rindex="${i}" style="padding: 4px 11px; border-radius: 13px; font-size: 12px; cursor: pointer; transition: all .15s;"></button>
            </div>
        </div>
    `).join('');

    if (!列表.dataset.bound) {
        列表.dataset.bound = '1';
        列表.addEventListener('click', function (e) {
            const b = e.target.closest('[data-rkind]');
            if (!b) return;
            切换外链范围(parseInt(b.dataset.rindex, 10), b.dataset.rkind);
        });
    }

    外链范围.forEach((_, i) => 刷新外链行(i));
}

function 刷新外链行(index) {
    const 列表 = document.getElementById('remoteList');
    if (!列表) return;
    const 行 = 列表.querySelector(`[data-remote-row="${index}"]`);
    if (!行) return;
    const 范围 = 外链范围[index] || { java: 1, inject: 0 };

    const 绘制 = (btn, on, onColor, onBg, onBorder) => {
        if (!btn) return;
        const 名 = btn.dataset.rkind === 'java' ? '云更新' : '注入';
        if (on) {
            btn.innerHTML = '<i class="fas fa-check"></i> ' + 名;
            btn.style.border = '1px solid ' + onBorder;
            btn.style.background = onBg;
            btn.style.color = onColor;
            btn.style.fontWeight = '600';
        } else {
            btn.innerHTML = 名;
            btn.style.border = '1px solid #e9ecef';
            btn.style.background = '#f8f9fa';
            btn.style.color = '#adb5bd';
            btn.style.fontWeight = '400';
        }
    };

    绘制(行.querySelector('[data-rkind="java"]'),   范围.java,   '#1e7e34', '#e8f5e9', '#28a745');
    绘制(行.querySelector('[data-rkind="inject"]'), 范围.inject, '#5f3dc4', '#f3f0ff', '#6741d9');
}

function 切换外链范围(index, key) {
    if (!外链范围[index]) 外链范围[index] = { java: 1, inject: 0 };
    const r = 外链范围[index];
    const other = key === 'java' ? 'inject' : 'java';
    if (r[key]) {
        if (!r[other]) {
            alert('云更新和注入至少要选一个', 'warning');
            return;
        }
        r[key] = 0;
    } else {
        r[key] = 1;
    }
    刷新外链行(index);
}

/** 提交外链登记（批量） */
async function 提交外链登记() {
    const urlsEl = document.getElementById('remoteUrls');
    const namesEl = document.getElementById('remoteNames');
    const noteEl = document.getElementById('remoteNote');

    const 链接数 = 外链行数('remoteUrls');
    const 名字数 = 外链行数('remoteNames');

    if (链接数 === 0) { alert('请填写下载直链', 'warning'); return; }
    if (链接数 !== 名字数) {
        alert('链接有 ' + 链接数 + ' 行，文件名有 ' + 名字数 + ' 行，必须一一对应', 'warning');
        return;
    }

    const 上传按钮 = document.getElementById('uploadBtn');
    if (上传按钮) 上传按钮.disabled = true;

    try {
        const formData = new FormData();
        formData.append('action', 'upload_so');
        formData.append('source', 'remote');
        formData.append('developer_username', 开发者UID);
        formData.append('password', 开发者密码);
        formData.append('token', 开发者Token);
        formData.append('app_id', 当前选中的应用ID);
        formData.append('remote_urls', urlsEl ? urlsEl.value : '');
        formData.append('remote_names', namesEl ? namesEl.value : '');
        formData.append('note', noteEl ? noteEl.value : '');
        formData.append('remote_scopes', JSON.stringify(外链范围));

        const resp = await fetch(获取API链接('Cloudupdate_上传.php'), {
            method: 'POST',
            body: formData
        });
        const text = await resp.text();
        let result = null;
        try { result = JSON.parse(text); } catch (e) { result = null; }

        if (!result) {
            alert('服务器返回异常：' + text.slice(0, 120), 'error');
            if (上传按钮) 上传按钮.disabled = false;
            return;
        }

        if (result.success) {
            alert('已登记 ' + ((result.data && result.data.count) || 链接数) + ' 条外链', 'success');
            关闭上传弹窗();
            if (typeof 加载云更新数据 === 'function') 加载云更新数据(1);
        } else {
            alert(result.message || '登记失败', 'error');
            if (上传按钮) 上传按钮.disabled = false;
        }
    } catch (e) {
        alert('请求失败：' + e.message, 'error');
        if (上传按钮) 上传按钮.disabled = false;
    }
}

