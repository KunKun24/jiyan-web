async function 注入_设置版本(releaseId, 当前版本) {
    const v = prompt('设置注入版本号（这套文件下发给客户端的版本标识）', 当前版本 || '');
    if (v === null) return;
    const 版本 = v.trim();
    if (!版本) { alert('版本号不能为空', 'warning'); return; }
    await 注入_动作({ action: 'set_version', release_id: releaseId, version: 版本 }, '版本号已设置');
}

async function 注入_设为当前(releaseId) {
    await 注入_动作({ action: 'set_current', release_id: releaseId }, '已设为当前版本');
}

async function 注入_删除(releaseId, version) {
    if (!confirm('确定删除注入版本 ' + version + ' 吗？\n删除后已下发到客户端的文件不会回滚。')) return;
    await 注入_动作({ action: 'delete', release_id: releaseId }, '已删除');
}

async function 注入_动作(payload, okMsg) {
    try {
        const fd = new FormData();
        fd.append('developer_username', 开发者UID);
        fd.append('password', 开发者安全密码 || '');
        fd.append('token', 开发者Token || '');
        fd.append('app_id', 当前选中的应用ID);
        Object.keys(payload).forEach(k => fd.append(k, payload[k]));

        const resp = await fetch(获取API链接('InjectAdmin.php'), { method: 'POST', body: fd, credentials: 'include' });
        const result = await resp.json();
        if (result.success) {
            alert(result.message || okMsg, true);
            加载注入数据(注入管理_当前页码);
        } else {
            alert(result.message || '操作失败', false);
        }
    } catch (e) {
        alert('操作出错：' + e.message, false);
    }
}

/* ---------------- 分页 / 搜索分派 ---------------- */

const 云更新_分页原函数 = {
    上一页: window.云更新管理_加载上一页,
    下一页: window.云更新管理_加载下一页,
    首页: window.云更新管理_加载首页,
    尾页: window.云更新管理_加载尾页
};

window.云更新管理_加载上一页 = function () {
    if (云更新类型 === 'inject') {
        if (注入管理_当前页码 > 1) 加载注入数据(注入管理_当前页码 - 1);
        return;
    }
    云更新_分页原函数.上一页();
};
window.云更新管理_加载下一页 = function () {
    if (云更新类型 === 'inject') {
        if (注入管理_当前页码 < 注入管理_总页数) 加载注入数据(注入管理_当前页码 + 1);
        return;
    }
    云更新_分页原函数.下一页();
};
window.云更新管理_加载首页 = function () {
    if (云更新类型 === 'inject') { 加载注入数据(1); return; }
    云更新_分页原函数.首页();
};
window.云更新管理_加载尾页 = function () {
    if (云更新类型 === 'inject') { 加载注入数据(注入管理_总页数); return; }
    云更新_分页原函数.尾页();
};

const 云更新_搜索原函数 = window.云更新管理_搜索关键词;
window.云更新管理_搜索关键词 = function () {
    if (云更新类型 === 'inject') {
        const box = document.getElementById('云更新管理_搜索框');
        注入管理_当前搜索 = box ? (box.value || '').trim() : '';
        加载注入数据(1);
        return;
    }
    云更新_搜索原函数();
};
