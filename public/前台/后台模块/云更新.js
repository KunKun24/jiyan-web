function selectTrafficPackage(packageId, packageName, price) {
    window.当前选中流量套餐 = { id: packageId, name: packageName, price: price };
    
    for (let i = 0; i < 5; i++) {
        const option = document.getElementById(`trafficPackage${i}`);
        if (option) {
            option.style.borderColor = '#ddd';
            option.style.background = 'white';
            option.classList.remove('active');
        }
    }
    
    const index = packageId - 1;
    const selected = document.getElementById(`trafficPackage${index}`);
    if (selected) {
        selected.style.borderColor = '#0b5e8a';
        selected.style.background = '#e6f3ff';
        selected.classList.add('active');
    }
    
    const confirmBtn = document.getElementById('confirmTrafficBtn');
    if (confirmBtn) {
        confirmBtn.disabled = false;
        confirmBtn.style.background = '#0b5e8a';
    }
}

async function confirmTrafficPurchase() {
    const selectedPackage = window.当前选中流量套餐;
    
    if (!selectedPackage) {
        alert('请先选择流量套餐');
        return;
    }
    
    if (!confirm(`确认充值 ${selectedPackage.name}？`)) return;
    
    try {
        const params = {
            action: 'recharge_traffic',
            password: 开发者安全密码,
            app_id: 当前选中的应用ID,
            package_id: selectedPackage.id
        };
        
        // 云更新通道统一走 Cloudupdate.php（协议 B：应用加密 + 应用签名）
        const result = await POSTCUPHP(params);
        
        if (result.success) {
            alert(result.message, 'success');
            closedatatopuppopupModal();
            加载云更新数据(云更新管理_当前页码);
        } else {
            alert(result.message || '充值失败', false);
        }
    } catch (error) {
        alert('充值失败：' + error.message, false);
    }
}
