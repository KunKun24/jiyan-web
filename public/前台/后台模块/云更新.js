/** 复制外链地址到剪贴板 */
function 云更新_复制外链(url) {
    if (!url) { alert('该文件没有外链地址', 'warning'); return; }
    const 完成 = () => alert('外链地址已复制', 'success');
    if (navigator.clipboard && window.isSecureContext) {
        navigator.clipboard.writeText(url).then(完成).catch(() => 云更新_复制外链_兜底(url, 完成));
    } else {
        云更新_复制外链_兜底(url, 完成);
    }
}

function 云更新_复制外链_兜底(url, 完成) {
    const ta = document.createElement('textarea');
    ta.value = url;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand('copy'); 完成(); }
    catch (e) { alert('复制失败，请手动选择复制', 'error'); }
    document.body.removeChild(ta);
}

