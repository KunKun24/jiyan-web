async function POSTCUPHP(params = {}) {
    try {
        const 应用ID = String(当前选中的应用ID || '');
        if (!应用ID) {
            return { success: false, message: '请先选择应用并等待配置加载完成' };
        }
        // 公共加解密函数读取全局配置；等待响应后必须先确认仍是同一份配置。
        const 请求配置 = {
            encrypt: typeof 当前选中的应用加密格式 === 'undefined' ? null : 当前选中的应用加密格式,
            key: typeof 当前选中的应用对接密钥 === 'undefined' ? null : 当前选中的应用对接密钥,
            sign: typeof 当前应用的签名类型 === 'undefined' ? null : 当前应用的签名类型,
            signKey: typeof 当前应用的签名密钥 === 'undefined' ? null : 当前应用的签名密钥,
            sequence: typeof 应用选择器_配置序号 === 'undefined' ? 0 : 应用选择器_配置序号
        };
        const IV = 生成随机IV();
        const encryptedData = APP_encryptRequestParams(params, IV, 'cloud');
        // rc 是每个请求的值，不能在响应阶段读取被其他并发请求覆盖的全局值。
        const 请求码 = String(window.__JY_LAST_RC || '');
        const requestBody = JSON.stringify({
            developer_username: 开发者UID,
            iv: IV,
            app_id: 应用ID,
            data: encryptedData
        });

        const response = await fetch(获取API链接('Cloudupdate.php'), {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json; charset=utf-8',
            },
            body: requestBody
        });
        const responseText = await response.text();
        if (应用ID !== String(当前选中的应用ID || '')
            || 请求配置.sequence !== (typeof 应用选择器_配置序号 === 'undefined' ? 0 : 应用选择器_配置序号)
            || 请求配置.encrypt !== (typeof 当前选中的应用加密格式 === 'undefined' ? null : 当前选中的应用加密格式)
            || 请求配置.key !== (typeof 当前选中的应用对接密钥 === 'undefined' ? null : 当前选中的应用对接密钥)
            || 请求配置.sign !== (typeof 当前应用的签名类型 === 'undefined' ? null : 当前应用的签名类型)
            || 请求配置.signKey !== (typeof 当前应用的签名密钥 === 'undefined' ? null : 当前应用的签名密钥)) {
            return { success: false, message: '应用配置已切换，请重试' };
        }
        // 此后直到验签结束无 await，公共函数使用的全局配置不会在中途切换。
        let result;
        try {
            result = JSON.parse(responseText);
        } catch (parseError) {
            try {
                result = JSON.parse(APP_解密(responseText, IV).trim());
            } catch (decryptError) {
                return { success: false, message: responseText || '服务器返回空响应' };
            }
        }
        if (!result || typeof result !== 'object' || Array.isArray(result) || typeof result.success !== 'boolean') {
            return { success: false, message: '返回响应格式错误' };
        }
        // 明文、密文及错误 JSON 统一验签；签名关闭由公共校验函数兼容。
        if (!APP_校验响应签名(result)) {
            return { success: false, message: '返回响应不可信,请检查签名状态' };
        }
        if (请求码 && result.data && Object.prototype.hasOwnProperty.call(result.data, 'rc')
            && String(result.data.rc) !== 请求码) {
            return { success: false, message: '返回响应请求码不匹配，请重试' };
        }
        return result;
    } catch (error) {
        return {
            success: false,
            message: '网络请求失败: ' + error.message
        };
    }
}




