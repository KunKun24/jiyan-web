function 处理文件选择(files) {
    const 有效文件 = [];
    const 错误信息 = [];
    
    files.forEach(file => {
        if (!/^[^.]*$|\.(so|bin|dat)$/i.test(file.name)) {
            错误信息.push(`${file.name}: 不是.so文件`);
            return;
        }
        
        if (file.size > 52 * 1024 * 1024) {
            错误信息.push(`${file.name}: 文件超过30MB限制`);
            return;
        }
        
        const 重复文件 = 已选文件列表.find(f => f.name === file.name && f.size === file.size);
        if (重复文件) {
            错误信息.push(`${file.name}: 文件已存在`);
            return;
        }
        
        有效文件.push(file);
    });
    
    if (有效文件.length > 0) {
        有效文件.forEach(() => 已选文件范围.push({ java: 默认发布范围.java, inject: 默认发布范围.inject }));
        已选文件列表.push(...有效文件);
        更新文件列表显示();
        
        const 拖拽区域 = document.getElementById('dragArea');
        if (拖拽区域) 拖拽区域.style.display = 'none';
    }
    
    if (错误信息.length > 0) {
        alert('以下文件不符合要求：\n' + 错误信息.join('\n'), 'warning');
    }
}

