async function 加载注入数据(page = 1) {
    if (!开发者UID || !开发者密码) { alert('请先登录', false); return; }

    const 动画 = document.getElementById('云更新管理_加载动画');
    if (动画) 动画.style.display = 'flex';

    if (!当前选中的应用ID) {
        const tbody = document.getElementById('云更新管理_TableBody');
        if (tbody) {
            tbody.innerHTML = `<tr><td colspan="7" style="text-align:center;padding:15vh;color:#666;">
                <i class="fas fa-ban" style="font-size:48px;margin-bottom:16px;display:block;opacity:.3;"></i>
                <div style="font-size:14px;">请先选择目标实例</div>
                <div style="font-size:12px;margin-top:8px;">点击右上角"选择对接实例"开始</div></td></tr>`;
        }
        if (动画) 动画.style.display = 'none';
        return;
    }

    try {
        const fd = new FormData();
        fd.append('action', 'list');
        fd.append('developer_username', 开发者UID);
        fd.append('password', 开发者安全密码 || '');
        fd.append('token', 开发者Token || '');
        fd.append('app_id', 当前选中的应用ID);
        fd.append('page', page);
        fd.append('page_size', 云更新管理_每页数量);
        if (注入管理_当前搜索) fd.append('search', 注入管理_当前搜索);

        const resp = await fetch(获取API链接('InjectAdmin.php'), { method: 'POST', body: fd, credentials: 'include' });
        const result = await resp.json();

        if (!result.success) {
            alert('加载注入发布记录失败：' + (result.message || '未知错误'), false);
            if (动画) 动画.style.display = 'none';
            return;
        }

        const data = result.data || {};
        const list = data.list || [];
        const pg = data.pagination || {};

        注入管理_当前页码 = page;
        注入管理_总页数 = pg.pages || 1;
        注入管理_总记录数 = pg.total || 0;

        注入_渲染表格(list);

        const 版本 = document.getElementById('云更新管理_版本');
        if (版本) 版本.textContent = data.current_version ? ('V' + data.current_version) : '未发布';
        const 总数 = document.getElementById('云更新管理_总记录数');
        if (总数) 总数.textContent = 注入管理_总记录数;
        const 码页 = document.getElementById('云更新管理_码页信息');
        if (码页) 码页.textContent = '第' + 注入管理_当前页码 + '/' + 注入管理_总页数 + '页';
        const 当前码 = document.getElementById('云更新管理_当前码页');
        if (当前码) 当前码.textContent = 注入管理_当前页码;

        if (动画) 动画.style.display = 'none';
    } catch (e) {
        alert('加载注入发布记录出错：' + e.message, false);
        if (动画) 动画.style.display = 'none';
    }
}

function 注入_渲染表格(list) {
    const tbody = document.getElementById('云更新管理_TableBody');
    if (!tbody) return;
    tbody.innerHTML = '';

    if (!list || list.length === 0) {
        tbody.innerHTML = `<tr><td colspan="7" style="text-align:center;padding:15vh;color:#666;">
            <i class="fas fa-box-open" style="font-size:48px;margin-bottom:16px;display:block;opacity:.3;"></i>
            <div style="font-size:14px;">还没有发布过注入文件</div>
            <div style="font-size:12px;margin-top:8px;">点右上角「上传文件」，勾上「注入」后即可下发到客户端</div></td></tr>`;
        return;
    }

    list.forEach((it) => {
        const tr = document.createElement('tr');
        const 当前 = Number(it.is_current) === 1;
        const 文件明细 = (it.files || []).map(f =>
            `<div style="font-size:12px;color:#868e96;">${escapeHtml(f.file_name)} · ${formatFileSize(f.file_size)}</div>`
        ).join('');

        tr.innerHTML = `
            <td style="text-align:center;">
                <i class="fas ${当前 ? 'fa-circle-check' : 'fa-circle'}"
                   style="color:${当前 ? '#37b24d' : '#dee2e6'};"></i>
            </td>
            <td>
                <div style="font-weight:600;">${it.version ? 'V' + escapeHtml(it.version) : '<span style="color:#e8590c;">未设置版本号</span>'}</div>
                <div style="font-size:12px;color:#868e96;">${escapeHtml(it.content || '—')}</div>
                <div style="margin-top:4px;">${文件明细}</div>
            </td>
            <td>${it.file_count}</td>
            <td>${formatFileSize(it.total_size)}</td>
            <td>${当前
                ? '<span style="background:#d3f9d8;color:#2b8a3e;padding:2px 8px;border-radius:8px;font-size:12px;">当前版本</span>'
                : '<span style="background:#f1f3f5;color:#868e96;padding:2px 8px;border-radius:8px;font-size:12px;">历史</span>'}</td>
            <td style="font-size:12px;color:#868e96;">${escapeHtml(it.created_at)}</td>
            <td>
                <div class="btn-group-compact">
                    <button class="按钮" style="padding:4px 10px;font-size:12px;" onclick="注入_设置版本(${it.release_id}, '${escapeHtml(it.version || '')}')">设置版本</button>
                    ${当前 ? '' : `<button class="按钮" style="padding:4px 10px;font-size:12px;" onclick="注入_设为当前(${it.release_id})">设为当前</button>`}
                    <button class="按钮" onclick="注入_删除(${it.release_id}, '${escapeHtml(it.version)}')"
                            style="padding:4px 10px;font-size:12px;background:#fff0f0;color:#e03131;">删除</button>
                </div>
            </td>`;
        tbody.appendChild(tr);
    });
}

